#!/usr/bin/env node
/* Writes docs/app-copy.txt: every sentence Receipts shows (demo data), so the
   plain-language reviewer agent can check them all in one go.

   Usage:
     node tools/export-app-copy.js
     kiro-cli chat --no-interactive --agent plain-language-reviewer --trust-tools=fs_read \
       "Review docs/app-copy.txt now, following your instructions."
*/
const fs = require("fs");
const path = require("path");
const { load } = require("../tests/load");

const root = path.join(__dirname, "..");
const g = load();
const A = g.RECEIPTS_ANALYSIS, W = g.RECEIPTS_WRITER;
const out = [];

const findings = A.runDetective();
const today = A.todayScore();
findings.forEach(f => out.push("[Patterns] " + W.writeFinding(f)));
out.push("[Today] " + W.writeTodayMessage(today));
// Also the "pacing day" wording, which the demo's latest day doesn't trigger.
out.push("[Today/pacing] " + W.writeTodayMessage({
  pacing: true, checked: ["recovery", "hrv", "sleep", "restingHr"],
  reasons: [{ k: "recovery", v: 41, base: 68 }, { k: "hrv", v: 44, base: 62 }, { k: "sleep", v: 5.1, base: 7.2 }, { k: "restingHr", v: 68, base: 60 }]
}));
["doctor", "patient"].forEach(aud => {
  const b = W.writeBrief(findings, today, aud);
  out.push(`[Brief/${aud}] intro: ${b.intro}`);
  b.patterns.forEach(p => {
    out.push(`[Brief/${aud}] ${p.sentence}`);
    if (p.question) out.push(`[Brief/${aud}] question: ${p.question}`);
  });
  b.patientQuestions.forEach(q => out.push(`[Brief/${aud}] ask: ${q}`));
});
A.insightStatus({ daily: [], availability: {}, symptomTaps: [], standingEvents: [] })
  .forEach(s => out.push(`[Missing data] ${s.label}: ${s.reason}`));

// Unwrap inline tags (<strong>, <em>, <code>, <u>, <a>) first, so sentences
// aren't cut into fragments at bold/italic words. (The reviewer agent flagged
// those fragments the first time; they were this script's fault, not the UI's.)
const html = fs.readFileSync(path.join(root, "index.html"), "utf8")
  .replace(/<script[\s\S]*?<\/script>/g, "").replace(/<!--[\s\S]*?-->/g, "")
  .replace(/<\/?(strong|em|code|u|a|span|b|i)\b[^>]*>/g, "");
[...html.matchAll(/>([^<>]{25,})</g)]
  .map(m => m[1].replace(/\s+/g, " ").trim())
  .filter(s => /[a-z]/.test(s))
  .forEach(s => out.push("[Screen text] " + s));

fs.mkdirSync(path.join(root, "docs"), { recursive: true });
fs.writeFileSync(path.join(root, "docs/app-copy.txt"),
  "# Every user-facing sentence in Receipts (generated by tools/export-app-copy.js; demo data)\n" + out.join("\n") + "\n");
console.log(`${out.length} lines -> docs/app-copy.txt`);
